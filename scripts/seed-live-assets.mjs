/* Copy the captured live images (public/images/live/*.jpg) into
   src/assets/nimo/<key>.jpg for every image key resolved via IMG_KEYS, so the
   <NimoImage> component serves optimized WebP locally instead of the remote
   URL. Then regenerates src/assets/nimo/images.mjs from whatever is on disk.

   Run after:  node scripts/download-images.mjs
               node scripts/apply-live-images.mjs
   Safe to re-run (skips existing files).
 */
import { mkdirSync, copyFileSync, existsSync, readFileSync, writeFileSync, readdirSync, rmSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  DESTINATIONS, HOTELS, WAHANA, HERO_SLIDES, MOMENTS, GALLERY, IMG, FB,
} from '../src/lib/data.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const ASSETS = join(ROOT, 'src', 'assets', 'nimo');
const LIVE = join(ROOT, 'public', 'images', 'live');
const AIMG = join(ROOT, 'public', 'aimg');

// Normalize live tokens to their source file path.
const tokenToFile = new Map();
for (const f of readdirSync(LIVE)) {
  const m = f.match(/AG8ngQ[A-Za-z0-9_-]+/);
  if (m) tokenToFile.set(m[0].slice(0, 28), join(LIVE, f));
}

// Key -> { url } for every unique image the site uses (mirrors images-seed).
const entries = new Map();
const add = (key, url) => {
  if (!url) return;
  if (!entries.has(url)) entries.set(url, { key, url });
};
for (const [k, url] of Object.entries(IMG)) add(k, url);
for (const [k, url] of Object.entries(FB)) add('fb-' + k, url);
for (const d of DESTINATIONS) {
  add(d.id + '-main', d.img);
  add(d.id + '-fb', d.fb);
  d.gallery?.forEach((g, i) => add(d.id + `-g${i + 1}`, g));
}
for (const h of HOTELS) {
  add(h.id + '-main', h.img);
  h.rooms.forEach(r => add(h.id + '-' + r.id, r.img));
}
WAHANA.forEach(w => add('wahana-' + w.name.toLowerCase().replace(/\s+/g, '-'), w.img));
HERO_SLIDES.forEach((s, i) => add('hero-' + (i + 1), s.img));
MOMENTS.forEach((m, i) => add('moment-' + (i + 1), m.img));
GALLERY.forEach((g, i) => add('gallery-' + (i + 1), g.img));
add('auth-bg', IMG.mist);

mkdirSync(ASSETS, { recursive: true });
let ok = 0, skip = 0, miss = 0;
const noLocal = [];

for (const { key, url } of entries.values()) {
  const urlToken = (url.match(/AG8ngQ[A-Za-z0-9_-]+\b/) || [url])[0].split('=')[0];
  const src = tokenToFile.get(urlToken.slice(0, 28));
  const dest = join(ASSETS, key + '.jpg');
  if (!src) { if (!existsSync(dest)) { noLocal.push(key); miss++; } continue; }
  if (existsSync(dest)) { skip++; continue; }
  copyFileSync(src, dest);
  ok++;
}
console.log(`Salin: ${ok} baru, ${skip} sudah ada, ${miss} tanpa file live.`);

// Regenerate images.mjs from disk.
const files = readdirSync(ASSETS)
  .filter(f => /\.(jpe?g|png|webp|avif)$/i.test(f))
  .sort((a, b) => a.localeCompare(b));
const imports = files.map(f => {
  const key = f.replace(/\.(jpe?g|png|webp|avif)$/i, '');
  return `  ${JSON.stringify(key)}: () => import('./' + ${JSON.stringify(f)}),`;
}).join('\n');
const listFile = join(ASSETS, 'images.mjs');
rmSync(listFile, { force: true });
writeFileSync(
  listFile,
  `/* Generated by scripts/seed-live-assets.mjs (setelah migrasi foto live).
     Maps image key -> lazy import so <NimoImage> can hand each file to
     astro:assets (WebP + sizes). */
export const nimoImages = {
${imports}
};

export const hasNimo = key => key in nimoImages;
`,
);
console.log(`images.mjs ditulis (${files.length} file lokal).`);
if (noLocal.length) console.log('Key tanpa file live (fallback remote): ' + noLocal.join(', '));

// Mirror each unique live photo to public/aimg/t<token>.jpg so client-rendered
// <img> tags (which can't run through astro:assets) can serve a local copy too.
mkdirSync(AIMG, { recursive: true });
let aimgOk = 0, aimgSkip = 0;
for (const [tok, src] of tokenToFile) {
  const dest = join(AIMG, 't' + tok + '.jpg');
  if (existsSync(dest)) { aimgSkip++; continue; }
  copyFileSync(src, dest);
  aimgOk++;
}
console.log(`public/aimg: ${aimgOk} baru, ${aimgSkip} sudah ada.`);